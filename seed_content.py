async def seed() -> None:
    await init_db()
    async with SessionLocal() as session:
        unit_order = 0
        for unit_data in CONTENT:
            unit_order += 1
            # идемпотентность по order
            unit = (
                await session.execute(
                    select(Unit).where(Unit.order == unit_order)
                )
            ).scalar_one_or_none()
            if unit is None:
                unit = Unit(
                    title=unit_data["title"],
                    order=unit_order,
                    description=unit_data.get("description"),
                )
                session.add(unit)
                await session.flush()

            lesson_order = 0
            for less in unit_data["lessons"]:
                lesson_order += 1
                existing = (
                    await session.execute(
                        select(Lesson)
                        .where(Lesson.unit_id == unit.id)
                        .where(Lesson.order == lesson_order)
                    )
                ).scalar_one_or_none()
                if existing is not None:
                    continue
                lesson = Lesson(
                    unit_id=unit.id,
                    title=less["title"],
                    order=lesson_order,
                    theory_text=less["theory"],
                )
                session.add(lesson)
                await session.flush()

                for qi, q in enumerate(less["quiz"]):
                    session.add(
                        QuizQuestion(
                            lesson_id=lesson.id,
                            question_text=q["q"],
                            options=json.dumps(q["options"], ensure_ascii=False),
                            correct_option=q["correct"],
                        )
                    )
                # аудио-заглушка (file_id пустой — хендлер не шлёт, пока нет файла)
                if less.get("audio"):
                    session.add(
                        AudioExample(
                            lesson_id=lesson.id,
                            file_id="",
                            description=less["audio"],
                        )
                    )
        await session.commit()

    # сводка
    async with SessionLocal() as session:
        n_units = (await session.execute(select(func.count()).select_from(Unit))).scalar()
        n_less = (await session.execute(select(func.count()).select_from(Lesson))).scalar()
        n_quiz = (await session.execute(select(func.count()).select_from(QuizQuestion))).scalar()
        print(f"✅ Seed готов: юнитов={n_units}, уроков={n_less}, квиз-вопросов={n_quiz}")


if __name__ == "__main__":
    asyncio.run(seed())
